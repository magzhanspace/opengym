#!/usr/bin/env node
/* Generates api/shared/library-data.js, the exercise index the API imports, from
 * frontend/src/lib/exercises-data.js.
 *
 *   node scripts/build-shared-assets.mjs           # write
 *   node scripts/build-shared-assets.mjs --check   # fail if stale (CI)
 *
 * The API needs the catalogue to check that every exercise id an imported plan references
 * exists, and to name exercises in webhooks and the calendar feed. Rather than teach the api
 * build to reach into frontend/, the index is generated and committed. Only an id, a name and
 * the taxonomy fields are kept.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const shared = join(root, 'api', 'shared');
const check = process.argv.includes('--check');

const outputs = [];

// --- library ---
{
  const src = join(root, 'frontend', 'src', 'lib', 'exercises-data.js');
  const { EXDB } = await import(pathToFileURL(src).href);
  // The well-known core comes first: the 1,324 exercises openGym always had, then the newer
  // lifts, and stretches, mobility, yoga and the like last.
  const LATE = new Set(['stretching', 'mobility', 'yoga', 'pilates', 'rehab', 'combat']);
  const catDir = join(root, 'catalogue', 'exercises');
  const classic = new Set();
  try {
    for (const f of readdirSync(catDir)) {
      if (JSON.parse(readFileSync(join(catDir, f), 'utf8')).textSource === 'exercisedb') classic.add(f.slice(0, -5));
    }
  } catch { /* no catalogue checked out: keep EXDB's order */ }
  const rank = e => (LATE.has(e.cat) ? 2 : classic.size && !classic.has(e.id) ? 1 : 0);
  const ranked = EXDB.map((e, i) => [rank(e), i, e]).sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  const index = ranked.map(([, , e]) => ({ id: e.id, n: e.n, bp: e.bp, tg: e.tg, eq: e.eq, ...(e.mk && e.mk !== 'none' ? { mk: e.mk } : {}) }));
  // Where the newer lifts and the late group start (library.js TIER_STARTS).
  const startOf = r => { const at = ranked.findIndex(x => x[0] >= r); return at < 0 ? index.length : at; };
  const body = '/* GENERATED by scripts/build-shared-assets.mjs from frontend/src/lib/exercises-data.js — do not edit. */\n' +
    `export const GENERATED_FROM = 'frontend/src/lib/exercises-data.js';\n` +
    `export const COUNT = ${index.length};\n` +
    `export const TIER_STARTS = [${startOf(1)}, ${startOf(2)}];\n` +
    'export const EXERCISES = ' + JSON.stringify(index) + ';\n';
  outputs.push({ file: join(shared, 'library-data.js'), body, note: `${index.length} exercises` });
}

let stale = 0;
for (const { file, body, note } of outputs) {
  const rel = file.slice(root.length + 1);
  if (check) {
    let current = null;
    try { current = readFileSync(file, 'utf8').replace(/\r\n/g, '\n'); } catch { /* missing counts as stale */ }
    if (current !== body) { stale++; console.error(`${rel} is out of date — run: node scripts/build-shared-assets.mjs`); }
    else console.log(`${rel} in sync (${note}).`);
  } else {
    writeFileSync(file, body);
    console.log(`Wrote ${rel} — ${note}, ${(body.length / 1024).toFixed(0)} KB.`);
  }
}
if (stale) process.exit(1);
